#!/usr/bin/env python3
"""Generate the glue that lets partly decompiled game code link on PC.

    python -I pc/tools/gen_link.py <ELF> <out_dir>

Scans src/<ELF>/**/*.c and writes:
  data_symbols.ld   D_XXXXXXXX = 0xXXXXXXXX;  (PS2 data stays at its PS2 address in guest memory)
  stubs.c           a stub for every func_XXXXXXXX the C calls but nobody has decompiled yet;
                    calling one stops the game with a clear message
Fails if two targets (overlays) define the same func_ name: overlays share address ranges,
so such functions need real names before the PC build can hold both.
"""
import re
import sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
DEF = re.compile(r"^[A-Za-z_][\w \t\*]*?\b(func_[0-9A-F]{8})\s*\([^;]*?\)\s*\{", re.M)


def main(elf, out):
    out = Path(out)
    out.mkdir(parents=True, exist_ok=True)
    defined, used_f, used_d = defaultdict(list), set(), set()
    for src in sorted((ROOT / "src" / elf).rglob("*.c")):
        text = src.read_text()
        target = src.relative_to(ROOT / "src" / elf).parts[0]
        for m in DEF.finditer(text):
            defined[m.group(1)].append(target)
        used_f.update(re.findall(r"\b(func_[0-9A-F]{8})\b", text))
        used_d.update(re.findall(r"\b(D_[0-9A-F]{8})\b", text))
    dup = {f: t for f, t in defined.items() if len(set(t)) > 1}
    if dup:
        sys.exit("same function name in several overlays (rename them first): "
                 + ", ".join(f"{f} in {'/'.join(sorted(set(t)))}" for f, t in sorted(dup.items())))
    (out / "data_symbols.ld").write_text(
        "/* generated by pc/tools/gen_link.py */\n" +
        "".join(f"{d} = 0x{d[2:]};\n" for d in sorted(used_d)))
    stubs = sorted(used_f - set(defined))
    (out / "stubs.c").write_text(
        "/* generated by pc/tools/gen_link.py: game functions not decompiled yet */\n"
        '#include "stubs.h"\n\n' +
        "".join(f"void {f}(void) {{ pc_unimplemented(0x{f[5:]}u, \"{f}\"); }}\n" for f in stubs))
    print(f"{elf}: {len(defined)} decompiled functions, {len(stubs)} stubs, {len(used_d)} data symbols")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
